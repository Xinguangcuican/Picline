import AppKit
import UniformTypeIdentifiers

/// Clipboard polling remains opt in. Image files can come from any folder;
/// only directory watching depends on the folders selected by the user.
@MainActor
final class ClipboardWatcher {
    static let ownType = NSPasteboard.PasteboardType("app.captureline.copied-image")
    private let onCapture: (CaptureInput) -> Void
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastCount: Int
    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        ownType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(pasteboard: NSPasteboard = .general, onCapture: @escaping (CaptureInput) -> Void) {
        self.pasteboard = pasteboard
        self.onCapture = onCapture
        lastCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        let inputs = Self.inputs(from: pasteboard.pasteboardItems ?? [])
        guard pasteboard.changeCount == count else { return }
        inputs.forEach(onCapture)
    }

    /// Inspect each item separately so a multi-display capture stays a batch.
    /// This is also usable with in-memory pasteboard items without reading the
    /// user's clipboard.
    static func inputs(from items: [NSPasteboardItem]) -> [CaptureInput] {
        guard !items.isEmpty, items.allSatisfy({ ignoredTypes.isDisjoint(with: $0.types) }) else { return [] }
        return items.compactMap { item in
            if item.types.contains(.fileURL) {
                guard let raw = item.string(forType: .fileURL), let url = URL(string: raw), url.isFileURL else { return nil }
                let file = url.standardizedFileURL.resolvingSymlinksInPath()
                // Finder can publish a TIFF icon for an ordinary file. The
                // presence of that representation does not make it an image.
                guard CaptureReceiver.imageExtensions.contains(file.pathExtension.lowercased()) else { return nil }
                var input = CaptureInput(payload: .file(file, .copy), source: .clipboard)
                // WeChat and other apps also publish the actual bitmap. Keep
                // it if their temporary file expires or cannot be read.
                input.fallbackImage = imageData(from: item)
                return input
            }
            if let data = imageData(from: item) {
                return CaptureInput(payload: .image(data), source: .clipboard)
            }
            return nil
        }
    }

    private static func imageData(from item: NSPasteboardItem) -> Data? {
        for type in [NSPasteboard.PasteboardType.png, .tiff,
                     .init(UTType.jpeg.identifier), .init(UTType.webP.identifier)] {
            if let data = item.data(forType: type), !data.isEmpty, data.count <= CaptureReceiver.maxBytes { return data }
        }
        return nil
    }
}
